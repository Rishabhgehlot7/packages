#!/usr/bin/env node
'use strict';
const { BoostReferralsManager } = require('../dist/index.js');
console.log('\n╔══════════════════════════════════════════════════╗');
console.log('║      @boostengine/referrals — CLI Demo           ║');
console.log('╚══════════════════════════════════════════════════╝\n');
const mgr = new BoostReferralsManager({ referrerRewardType: 'coins', referrerRewardValue: 200, refereeRewardType: 'coupon', refereeRewardValue: 10, codePrefix: 'BOOST' });
mgr.on('referral:created',   ({ referrerId, code }) => console.log(`  🔗 Link created for ${referrerId}: ${code}`));
mgr.on('referral:converted', ({ referrerId, newCustomerId }) => console.log(`  🎉 Conversion! ${referrerId} referred ${newCustomerId}`));
mgr.on('fraud:detected',     ({ code, flags }) => console.log(`  🚨 Fraud detected! Code: ${code} | Flags: ${flags.join(', ')}`));
console.log('▶ Step 1: Creating referral links...');
const aliceLink = mgr.createReferralLink('alice');
const bobLink   = mgr.createReferralLink('bob');
console.log('\n▶ Step 2: Share links for Alice:');
const share = mgr.getShareLinks(aliceLink.code, 'https://mystore.com');
console.log(`  WhatsApp: ${share.whatsapp.slice(0, 60)}...`);
console.log(`  Copy:     ${share.copyLink}`);
console.log('\n▶ Step 3: Tracking clicks...');
mgr.trackClick(aliceLink.code);
mgr.trackClick(aliceLink.code);
mgr.trackClick(aliceLink.code);
mgr.trackClick(bobLink.code);
console.log('\n▶ Step 4: Recording conversions...');
mgr.recordConversion({ referralCode: aliceLink.code, newCustomerId: 'user1', orderTotal: 1500, orderId: 'ORD-REF-001' });
mgr.recordConversion({ referralCode: aliceLink.code, newCustomerId: 'user2', orderTotal: 2000, orderId: 'ORD-REF-002' });
mgr.recordConversion({ referralCode: bobLink.code,   newCustomerId: 'user3', orderTotal: 800,  orderId: 'ORD-REF-003' });
console.log('\n▶ Step 5: Self-referral fraud test...');
mgr.recordConversion({ referralCode: aliceLink.code, newCustomerId: 'alice', orderTotal: 500 });
console.log('\n▶ Step 6: Leaderboard:');
mgr.getLeaderboard(3).forEach(e => console.log(`  #${e.rank} ${e.referrerId} — ${e.conversions} conversions | ₹${e.revenueGenerated} revenue`));
console.log('\n▶ Step 7: Alice stats:');
const stats = mgr.getReferralStats('alice');
console.log(`  Clicks: ${stats.totalClicks} | Conversions: ${stats.totalConversions} | CVR: ${stats.conversionRate}% | Reward: ${stats.totalRewardEarned} coins`);
console.log('\n✅ CLI demo complete!\n');
